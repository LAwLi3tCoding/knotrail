export type TextKey = keyof typeof zh;
export function resolveLocale(locale: Locale): 'zh-CN' | 'en' {
  return locale === 'system' ? (navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en') : locale;
}
